    export function showScreen() {
        scene.setBackgroundColor(15)
        scene.createRenderable(0, (target, camera) => {
            if (phase == 0) {
                center(target, "太陽能AI訓練師", 8, 5)
                center(target, "教AI什麼時候", 34, 1)
                center(target, "該幫太陽能板充電", 52, 1)
                center(target, "A=充電 B=不充電", 76, 9)
                center(target, "按A開始", 98, 7)
                return
            }
            if (phase == 3) {
                let t = SolarAI.getThreshold()
                center(target, "結果", 0, 5)
                center(target, "你答對 " + teacherScore + "/" + totalRounds, 17, 1)
                center(target, "AI答對 " + aiScore + "/" + totalRounds, 33, 1)
                center(target, "AI學到的門檻:" + (t < 0 ? "?" : "" + t), 50, 9)
                center(target, "真正的門檻:" + trueThreshold, 66, 9)
                if (aiScore >= 9) center(target, "太陽能大師!", 83, 5)
                else if (aiScore >= 7) center(target, "好老師", 83, 7)
                else center(target, "繼續訓練", 83, 2)
                center(target, "按A再玩一次", 102, 7)
                return
            }
            if (phase == 1) {
                center(target, "訓練 " + round + "/" + totalRounds, 0, 5)
            } else if (round > 0) {
                center(target, "AI測試 " + round + "/" + totalRounds, 0, 5)
            }
            if (phase == 2 && round == 0) {
                center(target, feedback, 52, feedbackColor)
                return
            }
            target.fillCircle(80, 30, 4 + Math.idiv(radiation, 125), 5)
            target.drawRect(10, 46, 140, 6, 1)
            target.fillRect(11, 47, Math.idiv(radiation * 138, 1000), 4, 5)
            center(target, "輻射值:" + radiation, 54, 1)
            if (phase == 1) {
                center(target, feedback, 74, feedbackColor)
                center(target, "A:充電 B:不充電", 102, 9)
            } else {
                center(target, "AI說:" + labelText(aiGuess), 70, 9)
                center(target, "正確答案:" + labelText(truth), 86, 1)
                center(target, feedback, 102, feedbackColor)
            }
        })
    }

