    let cacheKeys: string[] = []
    let cacheImgs: Image[] = []

    function hexVal(c: string): number {
        return "0123456789abcdef".indexOf(c)
    }

    function glyphImage(ch: string, color: number): Image {
        let key = ch + color
        let k = cacheKeys.indexOf(key)
        if (k >= 0) return cacheImgs[k]
        let img: Image = null
        let code = ch.charCodeAt(0)
        if (code < 128) {
            // 英文、數字、符號：8x16
            if (code <= 32 || code > 126) return null
            let adata = ASCII_DATA[code - 33]
            img = image.create(8, 16)
            for (let r = 0; r < 16; r++) {
                let v = hexVal(adata.charAt(r * 2)) * 16 + hexVal(adata.charAt(r * 2 + 1))
                for (let c = 0; c < 8; c++) {
                    if ((v >> (7 - c)) & 1) img.setPixel(c, r, color)
                }
            }
        } else {
            // 中文：16x16
            let idx = GLYPH_CHARS.indexOf(ch)
            if (idx < 0) return null
            let data = GLYPH_DATA[idx]
            img = image.create(16, 16)
            for (let r = 0; r < 16; r++) {
                let v = hexVal(data.charAt(r * 4)) * 4096 + hexVal(data.charAt(r * 4 + 1)) * 256 + hexVal(data.charAt(r * 4 + 2)) * 16 + hexVal(data.charAt(r * 4 + 3))
                for (let c = 0; c < 16; c++) {
                    if ((v >> (15 - c)) & 1) img.setPixel(c, r, color)
                }
            }
        }
        cacheKeys.push(key)
        cacheImgs.push(img)
        return img
    }

    function textWidth(text: string): number {
        let w = 0
        for (let i = 0; i < text.length; i++) {
            w += text.charCodeAt(i) < 128 ? 8 : 16
        }
        return w
    }

    function drawText(target: Image, text: string, x: number, y: number, color: number) {
        let cx = x
        for (let i = 0; i < text.length; i++) {
            let g = glyphImage(text.charAt(i), color)
            if (g) target.drawTransparentImage(g, cx, y)
            cx += text.charCodeAt(i) < 128 ? 8 : 16
        }
    }

    function center(target: Image, text: string, y: number, color: number) {
        drawText(target, text, Math.idiv(160 - textWidth(text), 2), y, color)
    }

